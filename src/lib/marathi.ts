function normalizeText(value: string) {
  return value
    .replace(/\u00a0/g, " ")
    .replace(/\u00c3\u00a2\u00e2\u201a\u00ac\u00e2\u20ac\u009d/g, "-")
    .replace(/\u00c3\u00a2\u00e2\u201a\u00ac\u00e2\u20ac\u0153/g, "-")
    .replace(/\u00e2\u20ac\u201d/g, "-")
    .replace(/\u00e2\u20ac\u201c/g, "-")
    .replace(/\u00c3\u00a2\u00e2\u201a\u00ac\u00c2\u00a6/g, "...")
    .replace(/\u00e2\u20ac\u00a6/g, "...")
    .replace(/\u00c3\u201a-/g, "-")
    .replace(/\u00c2-/g, "-")
    .replace(/\u00c3\u0192-/g, "x")
    .replace(/\u00c3\u201a\(c\)/g, "(c)")
    .replace(/\s+/g, " ")
    .trim();
}

function restoreWhitespace(original: string, translated: string) {
  const leading = original.match(/^\s*/)?.[0] ?? "";
  const trailing = original.match(/\s*$/)?.[0] ?? "";
  return `${leading}${translated}${trailing}`;
}

function toTitleCase(value: string) {
  return value.replace(/\b[a-z]/g, (letter) => letter.toUpperCase());
}

function shouldSkipWordFallback(value: string) {
  if (!/[A-Za-z]/.test(value)) return true;
  if (/^(https?:\/\/|www\.|[\w.-]+@[\w.-]+)/i.test(value)) return true;
  if (/\.(jpg|jpeg|png|webp|gif|svg|pdf|mp4|mov|webm|docx?|xlsx?|csv|zip)$/i.test(value)) return true;
  if (/^(TRD|CMP|KYC|MCR|POST|DB)-?\d+/i.test(value)) return true;
  if (/^[A-Z]-\d{2,}$/i.test(value)) return true;
  if (/^\+?\d[\d\s-]{7,}$/.test(value)) return true;
  return false;
}

function translateKnownWords(value: string) {
  if (shouldSkipWordFallback(value)) return value;

  return value.replace(/[A-Za-z][A-Za-z'-]*/g, (word) => {
    if (/^[A-Z]{2,}$/.test(word)) return word;
    const possessive = /'s$/i.test(word);
    const base = word.toLowerCase().replace(/'s$/i, "");
    const translated = wordTranslations[base];
    if (!translated) return word;
    return possessive ? `${translated}\u091a\u0947` : translated;
  });
}

export function translateToMarathi(value: string) {
  if (!value || !value.trim()) return value;
  const normalized = normalizeText(value);

  const direct = textTranslations[normalized] || textTranslations[toTitleCase(normalized.replace(/_/g, " "))];
  if (direct) {
    return restoreWhitespace(value, direct);
  }

  if (/^\d+\s+views$/i.test(normalized)) {
    return restoreWhitespace(value, normalized.replace(/views/i, "\u0926\u0943\u0936\u094d\u092f\u0947"));
  }

  const riskCleared = normalized.match(/^(.+?) has cleared the pending payment warning and is no longer marked high risk for that case\.$/i);
  if (riskCleared) {
    return restoreWhitespace(value, `${riskCleared[1]} \u092f\u093e\u0902\u0928\u0940 \u0925\u0915\u0940\u0924 \u092a\u0947\u092e\u0947\u0902\u091f \u0907\u0936\u093e\u0930\u093e \u092e\u093f\u091f\u0935\u0932\u093e \u0906\u0939\u0947. \u092f\u093e \u092a\u094d\u0930\u0915\u0930\u0923\u093e\u0938\u093e\u0920\u0940 \u0924\u0947 \u0906\u0924\u093e \u0909\u091a\u094d\u091a \u091c\u094b\u0916\u0940\u092e \u092e\u094d\u0939\u0923\u0942\u0928 \u0926\u0930\u094d\u0936\u0935\u0932\u0947 \u091c\u093e\u0923\u093e\u0930 \u0928\u093e\u0939\u0940\u0924.`);
  }

  const riskAlert = normalized.match(/^(.+?) has a new market-wide payment warning for Rs\. ([\d,]+(?:\.\d+)?)\.$/i);
  if (riskAlert) {
    return restoreWhitespace(value, `${riskAlert[1]} \u092f\u093e\u0902\u091a\u094d\u092f\u093e\u0935\u0930 \u0930\u0941. ${riskAlert[2]} \u0930\u0915\u092e\u0947\u0938\u093e\u0920\u0940 \u0928\u0935\u0940\u0928 \u092c\u093e\u091c\u093e\u0930-\u0935\u094d\u092f\u093e\u092a\u0940 \u092a\u0947\u092e\u0947\u0902\u091f \u0907\u0936\u093e\u0930\u093e \u0928\u094b\u0902\u0926\u0935\u0932\u093e \u0906\u0939\u0947.`);
  }

  if (normalized.startsWith("Welcome back, ")) {
    return restoreWhitespace(value, `\u092a\u0941\u0928\u094d\u0939\u093e \u0938\u094d\u0935\u093e\u0917\u0924 \u0906\u0939\u0947, ${normalized.replace("Welcome back, ", "")}`);
  }

  let translated = normalized;
  for (const [english, marathi] of replacements) {
    if (english.length < 4) continue;
    translated = translated.replaceAll(english, marathi);
  }

  const withWordFallback = translateKnownWords(translated);

  return withWordFallback === normalized ? value : restoreWhitespace(value, withWordFallback);
}

const originalText = new WeakMap<Text, string>();
const originalAttrs = new WeakMap<Element, Record<string, string>>();

export function translateDocumentToMarathi(root: ParentNode = document.body, lang: "en" | "mr" = "mr") {
  const textNodes: Text[] = [];
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement;
      if (!parent || parent.closest("[data-no-translate]") || ["SCRIPT", "STYLE", "NOSCRIPT", "TEXTAREA", "CODE"].includes(parent.tagName)) {
        return NodeFilter.FILTER_REJECT;
      }
      return node.textContent?.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
    },
  });

  while (walker.nextNode()) textNodes.push(walker.currentNode as Text);
  textNodes.forEach((node) => {
    const current = node.textContent ?? "";
    if (!originalText.has(node)) {
      const translated = translateToMarathi(current);
      if (translated === current) return;
      originalText.set(node, current);
      if (lang === "mr") node.textContent = translated;
      return;
    }

    const english = originalText.get(node) ?? "";
    const nextText = lang === "mr" ? translateToMarathi(english) : english;
    if (node.textContent !== nextText) node.textContent = nextText;
  });

  const attrNames = ["placeholder", "aria-label", "title"];
  root.querySelectorAll?.("input, textarea, button, a, [aria-label], [title]").forEach((el) => {
    const original = originalAttrs.get(el) ?? {};
    attrNames.forEach((attr) => {
      const value = el.getAttribute(attr);
      if (!value) return;
      if (!original[attr]) {
        const translated = translateToMarathi(value);
        if (translated === value) return;
        original[attr] = value;
        if (lang === "mr") el.setAttribute(attr, translated);
        return;
      }
      const nextValue = lang === "mr" ? translateToMarathi(original[attr]) : original[attr];
      if (value !== nextValue) el.setAttribute(attr, nextValue);
    });
    originalAttrs.set(el, original);
  });
}
